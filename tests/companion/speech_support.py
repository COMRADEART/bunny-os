class _ScriptedSession:
    def __init__(self, recognizer: "ScriptedRecognizer", request: SpeechInputRequest) -> None:
        self._recognizer = recognizer
        self._request = request
        self._revision = 0
        self._bytes = 0
        self._cancelled = False
        self._words: list[str] = []
        self.closed = False

    def accept(self, frames: bytes, *, position_seconds: float = 0.0) -> PartialTranscript | None:
        recognizer = self._recognizer
        recognizer.accepted_bytes += len(frames)
        if recognizer.accept_entered is not None:
            recognizer.accept_entered.set()
        if recognizer.accept_gate is not None:
            recognizer.accept_gate.wait(BARRIER_TIMEOUT)
        if recognizer.failure_mode == "crash-on-accept":
            raise RuntimeError("the scripted recogniser crashed on submitted frames")
        if self._cancelled or not frames:
            return None
        self._bytes += len(frames)
        words = recognizer.final_text.split()
        heard = min(len(words), 1 + self._bytes // recognizer.bytes_per_partial)
        if heard <= len(self._words):
            return None
        self._words = words[:heard]
        self._revision += 1
        try:
            return PartialTranscript(
                request_id=self._request.request_id,
                revision=self._revision,
                text=" ".join(self._words),
                provider_id=recognizer.provider_id,
                implementation_id=recognizer.declaration.implementation_id,
                confidence=0.5,
                position_seconds=position_seconds,
            )
        except Exception:  # noqa: BLE001 - over-bound partials are dropped, as vosk's are
            return None

    def finish(self) -> FinalTranscript:
        recognizer = self._recognizer
        if recognizer.finish_entered is not None:
            recognizer.finish_entered.set()
        if recognizer.finish_gate is not None:
            recognizer.finish_gate.wait(BARRIER_TIMEOUT)
        if recognizer.failure_mode == "crash-on-finish":
            raise RuntimeError("the scripted recogniser crashed at finalisation")
        if self._cancelled:
            raise RuntimeError("this recognition was cancelled and has no answer")
        text = recognizer.final_text if self._bytes else ""
        if recognizer.failure_mode == "empty":
            text = ""
        return FinalTranscript(
            request_id=self._request.request_id,
            session_id=self._request.session_id,
            text=text,
            provider_id=recognizer.provider_id,
            implementation_id=recognizer.declaration.implementation_id,
            language=self._request.language,
            confidence=0.9,
            audio_ended_at=self._bytes / max(1, self._request.bytes_per_second),
            recognition_mode="streaming",
        )

    def cancel(self) -> None:
        self._cancelled = True
        self._recognizer.cancelled.append(self._request.request_id)

    def close(self) -> None:
        self.closed = True
        self._recognizer.closed_sessions += 1


class ScriptedRecognizer:
    """A real :class:`companion.speech.recognizer.SpeechRecognizer` a test drives.

    Every §16 and §22 condition is a constructor argument, so a test reads as
    one line describing the recogniser it is pretending to have installed.
    """

    def __init__(
        self,
        provider_id: str = "scripted-recognizer",
        *,
        available: bool = True,
        supports_streaming: bool = True,
        supports_partials: bool = True,
        languages: Sequence[str] = ("en",),
        final_text: str = "count the words in this note",
        bytes_per_partial: int = 16_000,
        failure_mode: str = "",
        start_gate: threading.Event | None = None,
        start_entered: threading.Event | None = None,
        accept_gate: threading.Event | None = None,
        accept_entered: threading.Event | None = None,
        finish_gate: threading.Event | None = None,
        finish_entered: threading.Event | None = None,
        model_memory_bytes: int = 64 * 1024 * 1024,
    ) -> None:
        self.provider_id = provider_id
        self._available = available
        self.final_text = final_text
        self.bytes_per_partial = max(1, bytes_per_partial)
        self.failure_mode = failure_mode
        self.start_gate = start_gate
        self.start_entered = start_entered
        self.accept_gate = accept_gate
        self.accept_entered = accept_entered
        self.finish_gate = finish_gate
        self.finish_entered = finish_entered
        self.accepted_bytes = 0
        self.sessions: list[_ScriptedSession] = []
        self.cancelled: list[str] = []
        self.closed_sessions = 0
        self.closed = False
        self._declaration = RecognizerDeclaration(
            provider_id=provider_id,
            implementation_id=f"{provider_id}/test",
            local=True,
            languages=tuple(languages),
            locales=("en-GB", "en-US"),
            supports_streaming=supports_streaming,
            supports_partial_transcripts=supports_partials,
            provides_confidence=True,
            audio_formats=("raw-pcm-s16le",),
            sample_rates=(16_000, 22_050, 44_100, 48_000),
            resource_estimate=RecognizerResourceEstimate(
                model_memory_bytes=model_memory_bytes,
            ),
        )

    @property
    def declaration(self) -> RecognizerDeclaration:
        return self._declaration

    def set_available(self, value: bool) -> None:
        self._available = value

    def health(self, *, monotonic: float = 0.0, refresh: bool = False) -> RecognizerHealth:
        return RecognizerHealth(
            provider_id=self.provider_id,
            available=self._available and not self.closed,
            healthy=True,
            detail="" if self._available else "the scripted recogniser is unavailable",
            checked_at_monotonic=monotonic,
        )

    def start(self, request: SpeechInputRequest) -> _ScriptedSession:
        if self.start_entered is not None:
            self.start_entered.set()
        if self.start_gate is not None:
            self.start_gate.wait(BARRIER_TIMEOUT)
        if self.failure_mode == "crash-on-start":
            raise RuntimeError("the scripted recogniser could not start")
        session = _ScriptedSession(self, request)
        self.sessions.append(session)
        return session

    def close(self) -> None:
        self.closed = True


def scripted_registry(*recognizers: ScriptedRecognizer) -> RecognizerRegistry:
    return RecognizerRegistry(list(recognizers) or [ScriptedRecognizer()])


def wait_for(predicate: Callable[[], Any], timeout: float = BARRIER_TIMEOUT) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(0.005)
    return bool(predicate())


@dataclass
class WorkerHarness:
    """One capture worker with every collaborator reachable for assertions."""

    worker: Any
    backend: ScriptedCaptureBackend
    recognizer: ScriptedRecognizer
    router: Any
    policy: Any
    indicator: Any
    ledger: Any
    sink: RecordingSink
    journal: Any
    coordinator: Any

    def close(self) -> None:
        self.worker.close()


def build_worker(
    *,
    backend: ScriptedCaptureBackend | None = None,
    recognizer: ScriptedRecognizer | None = None,
    sink: RecordingSink | None = None,
    preferences: Any = None,
    coordinator: Any = None,
    journal: Any = None,
    observe: bool = True,
) -> WorkerHarness:
    """A worker over scripted collaborators, policy already observed capable."""
    from companion.speech.capture import CaptureRouter
    from companion.speech.confirmation import ConfirmationLedger
    from companion.speech.coordination import VoiceOutputCoordinator
    from companion.speech.indicator import ListeningIndicator
    from companion.speech.policy import (
        SpeechInputPolicy,
        SpeechInputPreferences,
        SpeechInputSignals,
    )
    from companion.speech.worker import CaptureWorker

    backend = backend or ScriptedCaptureBackend()
    recognizer = recognizer or ScriptedRecognizer()
    sink = sink or RecordingSink()
    router = CaptureRouter([backend])
    registry = scripted_registry(recognizer)
    policy = SpeechInputPolicy(preferences or SpeechInputPreferences())
    if observe:
        policy.observe(SpeechInputSignals(
            capture_device_available=True,
            recognizer_available=True,
            streaming_recognizer_available=recognizer.declaration.supports_streaming,
        ))
    indicator = ListeningIndicator()
    indicator.attach(sink)
    ledger = ConfirmationLedger()
    coordinator = coordinator or VoiceOutputCoordinator(None)
    worker = CaptureWorker(
        router=router,
        registry=registry,
        policy=policy,
        indicator=indicator,
        ledger=ledger,
        coordinator=coordinator,
        journal=journal,
    )
    return WorkerHarness(
        worker=worker, backend=backend, recognizer=recognizer, router=router,
        policy=policy, indicator=indicator, ledger=ledger, sink=sink,
        journal=journal, coordinator=coordinator,
    )
