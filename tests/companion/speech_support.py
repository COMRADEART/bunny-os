"""Fixtures for the speech-input suite: barriers, scripted devices, real PCM.

The two rules of :mod:`tests.companion.voice_support` run through everything
here. **Barriers, not sleeps**: every place a test must be *inside* an
operation — cancelling during capture, removing the device mid-utterance,
confirming while a retry lands — is a :class:`threading.Event` the fake waits
on and the test releases. **Real audio where audio is the point**: the frames
the scripted device delivers are genuine 16-bit PCM with a speech-shaped
envelope, generated by :func:`speech_pcm`, so the energy detector is exercised
on the waveform it will meet rather than on a list of numbers.

The scripted backend and recogniser implement the real contracts —
:class:`companion.speech.capture.CaptureBackend` and
:class:`companion.speech.recognizer.SpeechRecognizer` — rather than being
mocks with the methods a test happens to call, so the protocols cannot drift.
The scripted *handle* mirrors :class:`companion.speech.capture.CaptureHandle`'s
whole surface, buffer included, because the worker's capture loop reads all of
it.
"""

