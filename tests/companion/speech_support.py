#: How long any barrier in this suite waits before giving up: long enough that
#: a loaded machine does not fail spuriously, short enough that a deadlock is
#: reported rather than hung on.
BARRIER_TIMEOUT = 10.0


def speech_pcm(seconds: float, *, sample_rate: int = 16_000, channels: int = 1) -> bytes:
    """Raw 16-bit PCM whose loudness varies like speech.

    120 ms blocks alternating loud and quiet, matching
    :func:`tests.companion.voice_support.write_wav`'s envelope: several blocks
    cross the energy gate and several sit under it, so speech detection is a
    property of the waveform rather than of the fixture being uniformly loud.
    """
    frames = int(seconds * sample_rate)
    data = bytearray()
    for index in range(frames):
        moment = index / sample_rate
        block = int(moment / 0.12)
        level = (0.15, 0.9, 0.45, 0.6)[block % 4]
        value = level * math.sin(2 * math.pi * 220 * moment)
        sample = struct.pack("<h", int(max(-1.0, min(1.0, value)) * 32000))
        data += sample * channels
    return bytes(data)


def silence_pcm(seconds: float, *, sample_rate: int = 16_000, channels: int = 1) -> bytes:
    """Raw silence: zero-valued frames delivered on schedule, as a quiet room is."""
    return b"\x00\x00" * int(seconds * sample_rate) * channels


def make_request(
    *,
    request_id: str = "speechreq-1",
    session_id: str = "session-1",
    activation_source: str = "push-to-talk-button",
    maximum_capture_seconds: float = 8.0,
    initial_silence_seconds: float = 2.0,
    endpoint_silence_seconds: float = 0.4,
    **extra: Any,
) -> SpeechInputRequest:
    return SpeechInputRequest(
        request_id=request_id,
        session_id=session_id,
        activation_source=activation_source,
        maximum_capture_seconds=maximum_capture_seconds,
        initial_silence_seconds=initial_silence_seconds,
        endpoint_silence_seconds=endpoint_silence_seconds,
        **extra,
    )


def collect_events(worker: Any) -> tuple[list[Any], Callable[[], list[str]]]:
    """Subscribe to a worker and return the list plus a kinds-only view."""
    received: list[Any] = []
    lock = threading.Lock()

    def _observe(event: Any) -> None:
        with lock:
            received.append(event)

    worker.subscribe(_observe)

    def kinds() -> list[str]:
        with lock:
            return [item.kind for item in received]

    return received, kinds


class RecordingSink:
    """An indicator sink that displays by recording, and can refuse to."""

    def __init__(self, *, can_display: bool = True) -> None:
        self.can_display = can_display
        self.shown: list[dict[str, Any]] = []
        self.cleared: list[dict[str, Any]] = []
        self.shown_at: list[float] = []
        self.cleared_at: list[float] = []

    def show(self, state: Any) -> bool:
        if not self.can_display:
            return False
        self.shown.append(state.to_json())
        self.shown_at.append(time.monotonic())
        return True

    def clear(self, state: Any) -> bool:
        self.cleared.append(state.to_json())
        self.cleared_at.append(time.monotonic())
        return True


