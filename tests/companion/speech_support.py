class FrameScript:
    """The frames a scripted device will deliver, and when.

    A test pushes chunks (or queues them at construction) and the handle's
    ``read`` drains them. ``end()`` is the device going away: ``running``
    turns false and reads return nothing, which is exactly the shape a
    recorder's death presents to the worker. ``hold`` is a barrier: while
    set, reads return nothing but the device is alive — the state a test
    needs to be *inside* to cancel mid-capture deterministically.
    """

    def __init__(self, chunks: Sequence[bytes] = ()) -> None:
        self._chunks: list[bytes] = list(chunks)
        self._guard = threading.Lock()
        self._ended = False
        self.hold = threading.Event()
        self.first_read = threading.Event()

    def push(self, chunk: bytes) -> None:
        with self._guard:
            self._chunks.append(chunk)

    def end(self) -> None:
        with self._guard:
            self._ended = True

    @property
    def ended(self) -> bool:
        with self._guard:
            return self._ended

    def take(self) -> bytes:
        self.first_read.set()
        if self.hold.is_set():
            return b""
        with self._guard:
            if not self._chunks:
                return b""
            return self._chunks.pop(0)


class _ScriptedHandle:
    """A capture handle with no recorder behind it. The worker's whole surface."""

    def __init__(
        self,
        *,
        request: SpeechInputRequest,
        backend_id: str,
        device_id: str,
        script: FrameScript,
        fail_start: str = "",
        opened: threading.Event | None = None,
    ) -> None:
        self.request_id = request.request_id
        self.backend_id = backend_id
        self.device_id = device_id
        self.buffer = BoundedFrameBuffer(
            maximum_total_bytes=request.maximum_capture_bytes,
        )
        self._script = script
        self._fail_start = fail_start
        self._closed = False
        self._stopped = False
        self._guard = threading.RLock()
        self.requested_at = time.monotonic()
        self.opened_at = self.requested_at
        self.first_frame_at = 0.0
        if opened is not None:
            opened.set()

    @property
    def started(self) -> bool:
        return not self._fail_start

    @property
    def start_error(self) -> str:
        return self._fail_start

    @property
    def closed(self) -> bool:
        with self._guard:
            return self._closed

    @property
    def open_latency_seconds(self) -> float:
        return 0.0

    @property
    def first_frame_latency_seconds(self) -> float:
        return 0.0

    @property
    def bytes_captured(self) -> int:
        return self.buffer.total_bytes

    def running(self) -> bool:
        return not self._stopped and not self._script.ended and not self.buffer.exhausted

    def exit_code(self) -> int | None:
        return 0 if (self._stopped or self._script.ended) else None

    def read(self, *, timeout: float = 0.05) -> bytes:
        chunk = self._script.take()
        if chunk:
            if not self.first_frame_at:
                self.first_frame_at = time.monotonic()
            # Through the real bounded buffer, so overrun and budget
            # accounting are the production code's own.
            self.buffer.push(chunk)
            return self.buffer.read(timeout=0.0)
        if timeout:
            time.sleep(min(timeout, 0.005))
        return b""

    def stop(self) -> None:
        self._stopped = True

    def close(self) -> "_ScriptedHandle":
        with self._guard:
            self._closed = True
        self._stopped = True
        self.buffer.close()
        return self

    def describe(self) -> dict[str, Any]:
        return {"requestId": self.request_id, "closed": self.closed}


class ScriptedCaptureBackend:
    """A real :class:`companion.speech.capture.CaptureBackend` a test drives."""

    def __init__(
        self,
        backend_id: str = "scripted-capture",
        *,
        kind: str = "scripted",
        devices: Sequence[str] = ("scripted-mic",),
        monitors: Sequence[str] = (),
        reachable: bool = True,
        fail_start: str = "",
        script: FrameScript | None = None,
        opened: threading.Event | None = None,
    ) -> None:
        self.backend_id = backend_id
        self.kind = kind
        self._devices = list(devices)
        self._monitors = list(monitors)
        self._reachable = reachable
        self.fail_start = fail_start
        self.script = script or FrameScript()
        self.opened = opened
        self.closed = False
        self.opens = 0
        self.handles: list[_ScriptedHandle] = []

    def set_reachable(self, value: bool) -> None:
        self._reachable = value

    def set_devices(self, devices: Sequence[str]) -> None:
        self._devices = list(devices)

    def record(self, succeeded: bool) -> None:
        return None

    def health(self, *, monotonic: float = 0.0, refresh: bool = False) -> CaptureBackendHealth:
        usable = len(self._devices) if self._reachable else 0
        return CaptureBackendHealth(
            backend_id=self.backend_id,
            kind=self.kind,
            available=not self.closed,
            reachable=self._reachable,
            device_count=usable,
            default_device=self._devices[0] if self._devices and self._reachable else "",
            detail="" if self._reachable else "the scripted audio server is not answering",
            checked_at_monotonic=monotonic,
        )

    def discover(self) -> Sequence[CaptureDevice]:
        if not self._reachable:
            return ()
        found = [
            CaptureDevice(
                device_id=name, backend_id=self.backend_id, name=name,
                default=index == 0, state="RUNNING",
            )
            for index, name in enumerate(self._devices)
        ]
        found.extend(
            CaptureDevice(
                device_id=name, backend_id=self.backend_id, name=name,
                state="RUNNING", monitor=True,
            )
            for name in self._monitors
        )
        return tuple(found)

    def default_device(self) -> CaptureDevice | None:
        devices = [item for item in self.discover() if not item.monitor]
        return devices[0] if devices else None

    def supports(self, request: SpeechInputRequest) -> tuple[bool, str]:
        return True, ""

    def open(
        self,
        request: SpeechInputRequest,
        *,
        device_id: str = "",
        buffer: BoundedFrameBuffer | None = None,
    ) -> _ScriptedHandle:
        self.opens += 1
        handle = _ScriptedHandle(
            request=request,
            backend_id=self.backend_id,
            device_id=device_id or (self._devices[0] if self._devices else ""),
            script=self.script,
            fail_start=self.fail_start,
            opened=self.opened,
        )
        self.handles.append(handle)
        return handle

    def close(self) -> None:
        self.closed = True


