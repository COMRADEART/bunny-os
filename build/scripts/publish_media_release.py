"""Publish a qualified media tree as a GitHub release carrying the OS build.

The tree a live build leaves behind (`build/out/live/`, or an archived copy of
it) already knows everything true about itself: BUNNY-MANIFEST.json pins the
sha256 of every file it contains, provenance.json records the commit, the base
image and the machine that built it, boot-artifacts.json separates "image-builder
returned 0" from "the medium boots", and iso-digest.txt binds the result to one
exact medium. This script refuses to publish anything that fails those anchors,
because a release page is the one place a wrong byte gets a download button.

GitHub caps a single release asset at 2 GiB and the medium is ~5.7 GiB, so the
ISO is split into parts small enough to upload, every asset on the release is
checksummed in RELEASE-SHA256SUMS, and the notes carry the exact rejoin command.
The split is deterministic, so an interrupted run resumes onto the same draft
(found by scanning the release list — drafts are invisible to GitHub's by-tag
lookup): assets already present with the right size and digest are skipped,
mismatched ones are replaced, leftovers from an earlier attempt that this plan
no longer contains are deleted, and the release is flipped from draft to
published only after every asset has been verified against the local bytes.
A run that dies halfway leaves a draft, which nobody can download. A release
that is already published is never rewritten in place: an identical rerun
re-verifies and touches nothing, a divergent one is refused before the first
DELETE — never a half-true public page.

The git tag points at the manifest's sourceCommit, so "what does this release
contain" resolves to a commit, not to whatever HEAD was when someone ran this.

Transport is injectable (GithubTransport) so the test suite exercises the whole
flow — creation, resume, replacement, verification, publishing — offline.

Exit codes:
  0  published (or fully planned, under --dry-run)
  2  fail-closed refusal: the tree, the tag or the commit did not verify
  3  configuration missing (no token)
  4  GitHub refused something retries cannot fix
  5  uploaded assets do not verify against the local bytes
"""

from __future__ import annotations

import argparse
import hashlib
import http.client
import json
import os
import shutil
import sys
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath

GITHUB_API_HOST = "api.github.com"
GITHUB_UPLOAD_HOST = "uploads.github.com"
API_VERSION = "2022-11-28"
USER_AGENT = "bunny-os-publish-media"
#: GitHub refuses a single release asset at or above this size; every piece stays under it.
ASSET_LIMIT = 2 * 1024**3
DEFAULT_PART_MIB = 1900
DISK_SUFFIXES = {".iso", ".qcow2", ".raw", ".img", ".vmdk"}
#: Evidence the publisher demands regardless of what the manifest lists. A live
#: medium without these was never qualified as bootable, and "download" is a
#: claim only a booted medium earns.
REQUIRED_EVIDENCE = ("BUNNY-MANIFEST.json", "provenance.json", "boot-artifacts.json", "iso-digest.txt")
UPLOAD_ATTEMPTS = 4
#: Metadata calls are small; a stalled connection must surface as an error the
#: operator can rerun past, not as a silent infinite hang.
API_TIMEOUT = 60
#: Generated by this script; a tree carrying its own file of this name is a
#: prior release's leftover and would be silently contradicted by ours.
SUMS_NAME = "RELEASE-SHA256SUMS"


class PublishFailure(SystemExit):
    """A terminal failure carrying its own exit code."""

    code_value = 1
    label = "FAILED"

    def __init__(self, message: str):
        print(f"[{self.label}] {message}", file=sys.stderr)
        super().__init__(self.code_value)


class Refusal(PublishFailure):
    """Fail-closed: the tree, the tag or the commit did not verify (exit 2)."""

    code_value = 2
    label = "REFUSED"


class ConfigError(PublishFailure):
    """No token configured (exit 3)."""

    code_value = 3
    label = "CONFIG"


class ApiError(PublishFailure):
    """GitHub refused something retries cannot fix (exit 4)."""

    code_value = 4
    label = "GITHUB"


class VerifyFailure(PublishFailure):
    """Uploaded assets disagree with the local bytes (exit 5)."""

    code_value = 5
    label = "VERIFY"


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_of(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            value.update(chunk)
    return value.hexdigest()


def safe_relative(value: str, what: str) -> PurePosixPath:
    """The same path rules the manifest writer enforces, restated at the consumer."""
    relative = PurePosixPath(value)
    if (
        not value
        or "\\" in value
        or relative.is_absolute()
        or ".." in relative.parts
        or relative.as_posix() != value
    ):
        raise Refusal(f"{what} contains an unsafe path: {value!r}")
    return relative


# ---------------------------------------------------------------------------
# Tree validation — every check here is a way a release could lie.
# ---------------------------------------------------------------------------


def load_manifest(tree: Path) -> dict:
    manifest_path = tree / "BUNNY-MANIFEST.json"
    if not manifest_path.is_file():
        raise Refusal(f"no BUNNY-MANIFEST.json in {tree}; a tree without its own manifest cannot be published")
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise Refusal(f"BUNNY-MANIFEST.json is unreadable: {error}") from error
    if manifest.get("schemaVersion") != 1:
        raise Refusal(f"unsupported manifest schemaVersion: {manifest.get('schemaVersion')!r}")
    source_commit = manifest.get("sourceCommit")
    if (
        not isinstance(source_commit, str)
        or len(source_commit) != 40
        or any(c not in "0123456789abcdef" for c in source_commit)
    ):
        raise Refusal(f"manifest sourceCommit is not a 40-character sha: {source_commit!r}")
    image_version = manifest.get("imageVersion")
    if not isinstance(image_version, str) or not image_version.strip():
        raise Refusal(f"manifest imageVersion is missing: {image_version!r}")
    files = manifest.get("files")
    if not isinstance(files, list) or not files:
        raise Refusal("manifest carries no files list")
    seen: set[str] = set()
    for index, item in enumerate(files):
        if not isinstance(item, dict) or not isinstance(item.get("path"), str) or not isinstance(item.get("sha256"), str):
            raise Refusal(f"manifest entry {index} is malformed: {item!r}")
        safe_relative(item["path"], f"manifest entry {index}")
        if item["path"] in seen:
            raise Refusal(f"manifest repeats a path: {item['path']}")
        seen.add(item["path"])
    return manifest


def verify_manifest_files(tree: Path, manifest: dict) -> dict[str, dict]:
    """Hash every listed file; return path -> entry. Any drift is a refusal."""
    verified: dict[str, dict] = {}
    for item in manifest["files"]:
        target = tree.joinpath(*PurePosixPath(item["path"]).parts)
        if not target.is_file():
            raise Refusal(f"manifest lists a file the tree does not have: {item['path']}")
        actual = sha256_of(target)
        if actual != item["sha256"]:
            raise Refusal(
                f"digest mismatch for {item['path']}: manifest {item['sha256']} != actual {actual}"
            )
        verified[item["path"]] = item
    return verified


def find_the_medium(tree: Path, verified: dict[str, dict]) -> tuple[str, Path]:
    """Exactly one disk image may be published, and it must be the manifest's own."""
    disks = sorted(p for p in verified if PurePosixPath(p).suffix.lower() in DISK_SUFFIXES)
    if len(disks) != 1:
        raise Refusal(f"expected exactly one medium in the manifest, found {len(disks)}: {disks}")
    medium_rel = disks[0]
    # A second .iso sitting in the tree but outside the manifest would ride the
    # release page next to a manifest that says nothing about it.
    for candidate in tree.rglob("*"):
        if (
            candidate.is_file()
            and candidate.suffix.lower() in DISK_SUFFIXES
            and candidate.relative_to(tree).as_posix() not in verified
        ):
            raise Refusal(
                f"unmanifested medium in the tree: {candidate.relative_to(tree).as_posix()}; "
                "archive it elsewhere or rebuild the manifest"
            )
    return medium_rel, tree.joinpath(*PurePosixPath(medium_rel).parts)


def require_evidence(tree: Path, verified: dict[str, dict]) -> None:
    """Demand the qualification records, pinning any that the manifest omitted."""
    for name in REQUIRED_EVIDENCE:
        if name in verified:
            continue
        target = tree / name
        if not target.is_file():
            raise Refusal(f"{name} is required to publish a medium and is not in the tree")
        verified[name] = {"path": name, "sha256": sha256_of(target), "critical": False}


def cross_check_provenance(tree: Path, manifest: dict, medium_rel: str) -> dict:
    try:
        provenance = json.loads((tree / "provenance.json").read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise Refusal(f"provenance.json is unreadable: {error}") from error
    if provenance.get("sourceCommit") != manifest["sourceCommit"]:
        raise Refusal(
            f"provenance sourceCommit {provenance.get('sourceCommit')!r} disagrees with "
            f"the manifest's {manifest['sourceCommit']!r}"
        )
    if provenance.get("archiveOnly"):
        raise Refusal("provenance says archiveOnly: an archive-only build produced no bootable medium")
    artifacts = provenance.get("artifacts")
    if not isinstance(artifacts, list):
        raise Refusal("provenance carries no artifacts list")
    medium_entry = None
    disk_paths = []
    for item in artifacts:
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            raise Refusal(f"malformed provenance artifact entry: {item!r}")
        if PurePosixPath(item["path"]).suffix.lower() in DISK_SUFFIXES:
            disk_paths.append(item["path"])
            medium_entry = item
    expected = tree.joinpath(*PurePosixPath(medium_rel).parts)
    if medium_entry is None or disk_paths != [medium_rel]:
        raise Refusal(
            f"provenance disk artifacts {disk_paths} do not name exactly the manifest medium {medium_rel}"
        )
    if medium_entry.get("size") != expected.stat().st_size or medium_entry.get("sha256") != sha256_of(expected):
        raise Refusal(f"provenance size/digest disagrees with the medium: {medium_entry}")
    return provenance


def check_boot_verdict(tree: Path) -> dict:
    try:
        report = json.loads((tree / "boot-artifacts.json").read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise Refusal(f"boot-artifacts.json is unreadable: {error}") from error
    if report.get("status") != "PASS":
        failures = [
            c.get("check")
            for c in report.get("checks", [])
            if isinstance(c, dict) and c.get("status") == "FAIL"
        ]
        raise Refusal(
            f"boot-artifacts.json verdict is {report.get('status')!r}, not PASS "
            f"(failing checks: {failures}); a medium nobody booted gets no download button"
        )
    return report


def check_iso_digest_file(tree: Path, medium_digest: str) -> None:
    text = (tree / "iso-digest.txt").read_text(encoding="utf-8", errors="replace")
    recorded = {line.split(maxsplit=1)[0] for line in text.splitlines() if line.split()}
    if medium_digest not in recorded:
        raise Refusal(
            f"iso-digest.txt does not record the medium digest {medium_digest}; "
            "the tree may belong to a different build"
        )


# ---------------------------------------------------------------------------
# Asset planning — slice the medium without materializing the slices.
#
# Parts are never written to disk: every asset names a byte range of the
# medium itself, and the uploader streams each range straight off the file.
# A 5.7 GiB medium therefore costs no scratch space at all — which matters
# because the builder this runs on has had its disk refuse to grow — and the
# split stays trivially deterministic because it is arithmetic, not I/O.
# ---------------------------------------------------------------------------


class SliceReader:
    """A bounded reader over one byte range of a file, shaped for http.client."""

    def __init__(self, handle, offset: int, size: int):
        self._handle = handle
        self._remaining = size
        handle.seek(offset)

    def read(self, n: int = -1) -> bytes:
        if self._remaining <= 0:
            return b""
        if n is None or n < 0:
            n = self._remaining
        data = self._handle.read(min(n, self._remaining))
        self._remaining -= len(data)
        return data


def plan_medium_parts(medium: Path, medium_size: int, part_bytes: int) -> list[dict]:
    """One sequential pass over the medium; each range gets its digest."""
    count = (medium_size + part_bytes - 1) // part_bytes
    width = max(2, len(str(count - 1)))
    parts = []
    offset = 0
    with medium.open("rb") as source:
        for index in range(count):
            length = min(part_bytes, medium_size - offset)
            digest = hashlib.sha256()
            consumed = 0
            while consumed < length:
                block = source.read(min(1024 * 1024, length - consumed))
                if not block:
                    raise Refusal(f"medium shrank while hashing: {medium}")
                digest.update(block)
                consumed += len(block)
            parts.append({
                "name": f"{medium.name}.part-{index:0{width}d}",
                "source": str(medium), "offset": offset, "size": length,
                "sha256": digest.hexdigest(),
            })
            offset += length
    if offset != medium_size:
        raise Refusal("split accounting lost bytes; refusing to continue")
    return parts


def plan_assets(tree: Path, verified: dict[str, dict], medium_rel: str, medium: Path,
                work_dir: Path, part_bytes: int) -> dict:
    medium_size = medium.stat().st_size
    # verify_manifest_files already read every byte and pinned the digest;
    # nothing here may pay for a second opinion it already has.
    medium_sha = verified[medium_rel]["sha256"]
    assets: dict[str, dict] = {}
    if medium_size > part_bytes:
        for part in plan_medium_parts(medium, medium_size, part_bytes):
            assets[part["name"]] = part
    else:
        assets[medium.name] = {
            "name": medium.name, "source": str(medium), "offset": 0,
            "size": medium_size, "sha256": medium_sha,
        }
    for rel, item in sorted(verified.items()):
        if rel == medium_rel or PurePosixPath(rel).suffix.lower() in DISK_SUFFIXES:
            continue
        name = PurePosixPath(rel).name
        if name == SUMS_NAME:
            # The manifest writer pins every file it finds, so a prior release's
            # sums file would be verified as tree truth here and then silently
            # overwritten by ours below — a manifest contradicting its own asset.
            raise Refusal(
                f"the tree carries its own {SUMS_NAME} ({rel}); the publisher generates "
                "one itself — remove or rename the tree copy")
        if name in assets:
            raise Refusal(f"two files would upload under the asset name {name!r}; rename one in the tree")
        assets[name] = {
            "name": name, "path": tree.joinpath(*PurePosixPath(rel).parts),
            "size": (tree.joinpath(*PurePosixPath(rel).parts)).stat().st_size,
            "sha256": item["sha256"],
        }
    for asset in assets.values():
        if asset["size"] >= ASSET_LIMIT:
            raise Refusal(
                f"asset {asset['name']} is {asset['size']:,} bytes, at or over GitHub's "
                f"{ASSET_LIMIT:,}-byte per-file cap"
            )
    sums_name = SUMS_NAME
    sums_body = "".join(f"{a['sha256']}  {a['name']}\n" for a in sorted(assets.values(), key=lambda x: x["name"]))
    sums_path = work_dir / sums_name
    # Bytes, never text mode: a text write turns every \n into \r\n on Windows
    # and the file stops matching the digest and size planned for it.
    sums_path.write_bytes(sums_body.encode("utf-8"))
    assets[sums_name] = {
        "name": sums_name, "path": sums_path,
        "size": len(sums_body.encode("utf-8")),
        "sha256": hashlib.sha256(sums_body.encode("utf-8")).hexdigest(),
    }
    return {
        "assets": assets,
        "medium": {"rel": medium_rel, "name": medium.name,
                   "size": medium_size, "sha256": medium_sha},
    }


# ---------------------------------------------------------------------------
# Notes — the release page states what the evidence states, nothing more.
# ---------------------------------------------------------------------------


def render_notes(context: dict) -> str:
    medium = context["plan"]["medium"]
    manifest = context["manifest"]
    provenance = context["provenance"]
    boot = context["boot"]
    assets = context["plan"]["assets"]
    # Classify structurally, never by ".part-" appearing in the name: an
    # evidence file that merely contains that substring would otherwise ride
    # into the rejoin command users paste verbatim.
    part_names = {a["name"] for a in assets.values() if "offset" in a} - {medium["name"]}
    parts = [a for n, a in sorted(assets.items()) if n in part_names]
    evidence = [n for n, a in sorted(assets.items())
                if n not in part_names and n not in (medium["name"], SUMS_NAME)]
    builder = provenance.get("builder", {})
    lines = [
        f"## Bunny OS `{manifest['imageVersion']}`",
        "",
        "The OS build for the commit below, published from a media tree whose",
        "contents were re-verified against their own build-time manifests immediately",
        "before upload.",
        "",
        "| | |",
        "|---|---|",
        f"| Medium | `{medium['name']}` |",
        f"| Source commit | `{manifest['sourceCommit']}` |",
        f"| Image version | `{manifest['imageVersion']}` |",
        f"| Base image | `{provenance.get('baseImage', 'unknown')}` |",
        f"| Built (UTC) | {provenance.get('recordedAt', 'unknown')} |",
        f"| Builder | {builder.get('distribution', 'unknown')}, kernel {builder.get('kernel', 'unknown')}, "
        f"{builder.get('virtualization', 'unknown')} ({builder.get('architecture', 'unknown')}) |",
        f"| Size | {medium['size']:,} bytes |",
        f"| SHA-256 | `{medium['sha256']}` |",
        "",
        "### Downloading",
        "",
    ]
    if parts:
        lines += [
            f"The medium exceeds GitHub's 2 GiB per-asset limit and ships as {len(parts)} parts.",
            "Reassemble it, then check every file on this release:",
            "",
            "```sh",
            "cat \\",
        ]
        lines += [f"  '{p['name']}' \\" for p in parts[:-1]]
        lines += [
            f"  '{parts[-1]['name']}' > '{medium['name']}'",
            "sha256sum -c RELEASE-SHA256SUMS",
            "```",
            "",
        ]
    else:
        lines += [
            f"Download `{medium['name']}` and verify it:",
            "",
            "```sh",
            "sha256sum -c RELEASE-SHA256SUMS",
            "```",
            "",
        ]
    lines += [
        "### Verification chain",
        "",
        f"- `boot-artifacts.json`: **{boot.get('status')}** across {len(boot.get('checks', []))} checks that read "
        "the assembled ISO back the way firmware will — volume label, GRUB entries, kernel and initramfs digests.",
        "- `BUNNY-MANIFEST.json` pins the sha256 of every file published here; its `critical` entries are the "
        "medium and its provenance.",
        "- `provenance.json` records the source commit, base image, tool versions and the machine that built it.",
        f"- `{SUMS_NAME}` covers every asset on this release; the expected medium digest is in the table above.",
        "",
    ]
    if evidence:
        lines += ["Also carried: " + ", ".join(f"`{n}`" for n in evidence) + ".", ""]
    lines += [
        "---",
        f"Published by `build/scripts/publish_media_release.py` at {utc_now()}.",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# GitHub transport — real HTTP here, a recording fake in the test suite.
# ---------------------------------------------------------------------------


class GithubTransport:
    def __init__(self, token: str, repo_path: str):
        self.token = token
        self.repo_path = repo_path

    def _headers(self, extra: dict | None = None) -> dict:
        headers = {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": API_VERSION,
            "User-Agent": USER_AGENT,
        }
        if extra:
            headers.update(extra)
        return headers

    def api(self, method: str, path: str, payload: dict | None = None) -> tuple[int, dict | list | None]:
        request = urllib.request.Request(
            f"https://{GITHUB_API_HOST}{path}",
            data=json.dumps(payload).encode("utf-8") if payload is not None else None,
            method=method,
            headers=self._headers({"Content-Type": "application/json"} if payload is not None else None),
        )
        try:
            with urllib.request.urlopen(request, timeout=API_TIMEOUT) as response:
                body = response.read()
                return response.status, json.loads(body) if body else None
        except urllib.error.HTTPError as error:
            return error.code, self._safe_json(error)
        except urllib.error.URLError as error:
            raise ApiError(f"{method} {path}: network failure: {error.reason}") from error

    @staticmethod
    def _safe_json(error: urllib.error.HTTPError) -> dict | None:
        try:
            return json.loads(error.read().decode("utf-8"))
        except Exception:
            return None

    @staticmethod
    def _upload_connection() -> http.client.HTTPSConnection:
        """The upload host, tunneled through an HTTPS proxy when one is set.

        http.client ignores the proxy environment that urllib honors for the
        metadata calls; without this a proxied builder sails through every
        metadata check and then cannot reach uploads.github.com at all.
        """
        proxy = urllib.request.getproxies().get("https")
        if proxy:
            parsed = urllib.parse.urlsplit(proxy)
            connection = http.client.HTTPSConnection(
                parsed.hostname or "", parsed.port or 80, timeout=600)
            connection.set_tunnel(GITHUB_UPLOAD_HOST)
            return connection
        return http.client.HTTPSConnection(GITHUB_UPLOAD_HOST, timeout=600)

    def upload(self, release_id: int, asset: dict) -> tuple[int, dict | None]:
        """Stream one asset body to the release-upload host.

        Range assets (medium parts) read straight off the medium; file assets
        read whole. Either way the bytes never sit in memory or on scratch.
        """
        if "source" in asset:
            handle = open(asset["source"], "rb")
            body = SliceReader(handle, asset["offset"], asset["size"])
        else:
            handle = open(asset["path"], "rb")
            body = handle
        connection = self._upload_connection()
        try:
            quoted = urllib.parse.quote(asset["name"], safe="")
            connection.request(
                "POST",
                f"/repos/{self.repo_path}/releases/{release_id}/assets?name={quoted}",
                body=body,
                headers=self._headers({
                    "Content-Type": "application/octet-stream",
                    "Content-Length": str(asset["size"]),
                }),
            )
            response = connection.getresponse()
            payload_bytes = response.read()
            try:
                payload = json.loads(payload_bytes) if payload_bytes else None
            except json.JSONDecodeError:
                payload = None
            return response.status, payload
        finally:
            connection.close()
            handle.close()


# ---------------------------------------------------------------------------
# The publishing flow.
# ---------------------------------------------------------------------------


class Publisher:
    def __init__(self, config: dict, transport: GithubTransport):
        self.config = config
        self.transport = transport

    # -- API helpers -------------------------------------------------------

    def call(self, method: str, path: str, payload: dict | None = None) -> dict | list | None:
        status, body = self.transport.api(method, path, payload)
        if status >= 300:
            excerpt = json.dumps(body)[:400] if body else "(no body)"
            raise ApiError(f"{method} {path} -> HTTP {status}: {excerpt}")
        return body

    def quiet(self, method: str, path: str, payload: dict | None = None) -> tuple[int, dict | list | None]:
        return self.transport.api(method, path, payload)

    def commit_on_origin(self, commit: str) -> None:
        """404 means genuinely absent; anything else is an auth or repo fault.

        Collapsing a 401 onto "not pushed" once told an operator with an
        expired token to push a commit that was already on origin.
        """
        status, _ = self.quiet("GET", f"/repos/{self.config['repo']}/commits/{commit}")
        if status == 200:
            return
        if status == 404:
            raise Refusal(
                f"commit {commit} is not visible on {self.config['repo']}; push the candidate first — "
                "a release tagged at an unreachable commit is unreachable history")
        raise ApiError(f"could not look up commit {commit}: HTTP {status}")

    def tag_points_at(self, tag: str) -> str | None:
        """The commit a tag names, following one level of annotated-tag indirection."""
        status, ref = self.quiet("GET", f"/repos/{self.config['repo']}/git/ref/tags/{urllib.parse.quote(tag, safe='')}")
        if status == 404:
            return None
        if status != 200:
            raise ApiError(f"could not read refs/tags/{tag}: HTTP {status}")
        obj = (ref or {}).get("object", {})
        if obj.get("type") == "tag":
            status, tag_obj = self.quiet("GET", f"/repos/{self.config['repo']}/git/tags/{obj.get('sha')}")
            if status != 200:
                raise ApiError(f"could not dereference annotated tag {tag}: HTTP {status}")
            return (tag_obj or {}).get("object", {}).get("sha")
        return obj.get("sha")

    def release_for_tag(self, tag: str) -> dict | None:
        """The release for a tag — including drafts, which the by-tag endpoint hides.

        GitHub's GET /releases/tags/{tag} only ever returns the *published*
        release; an interrupted or --stay-draft run leaves a draft that is
        invisible there. Adopting it instead of minting another one is what
        makes "rerun to resume" true: without the scan below, every rerun of a
        dead run created a second draft and re-uploaded the whole medium.
        """
        quoted = urllib.parse.quote(tag, safe="")
        status, release = self.quiet("GET", f"/repos/{self.config['repo']}/releases/tags/{quoted}")
        if status == 200:
            return release
        if status != 404:
            raise ApiError(f"could not look up a release for tag {tag}: HTTP {status}")
        page = 1
        while True:
            status, batch = self.quiet(
                "GET", f"/repos/{self.config['repo']}/releases?per_page=100&page={page}")
            if status != 200:
                raise ApiError(f"could not list releases of {self.config['repo']}: HTTP {status}")
            for item in batch or []:
                if item.get("tag_name") == tag:
                    return item
            if len(batch or []) < 100:
                return None
            page += 1

    def existing_assets(self, release_id: int) -> dict[str, dict]:
        assets: dict[str, dict] = {}
        page = 1
        while True:
            status, batch = self.quiet(
                "GET", f"/repos/{self.config['repo']}/releases/{release_id}/assets?per_page=100&page={page}")
            if status != 200:
                raise ApiError(f"could not list assets of release {release_id}: HTTP {status}")
            for item in batch or []:
                assets[item["name"]] = item
            if len(batch or []) < 100:
                return assets
            page += 1

    # -- steps -------------------------------------------------------------

    def upload_with_retry(self, release_id: int, asset: dict) -> tuple[int, dict | None]:
        """One retry policy for every transport. Server faults (5xx) and dropped
        connections retry with capped backoff; client mistakes (4xx) come back."""
        last_error = "unknown"
        for attempt in range(1, UPLOAD_ATTEMPTS + 1):
            try:
                status, body = self.transport.upload(release_id, asset)
                if status < 500:
                    return status, body
                last_error = f"HTTP {status}"
            except (OSError, http.client.HTTPException) as error:
                last_error = str(error) or error.__class__.__name__
            if attempt < UPLOAD_ATTEMPTS:
                time.sleep(2 * attempt)
        raise ApiError(f"upload of {asset['name']} failed after {UPLOAD_ATTEMPTS} attempts: {last_error}")

    def run(self, context: dict) -> dict:
        commit = context["manifest"]["sourceCommit"]
        tag = context["tag"]
        repo = self.config["repo"]
        print(f"[publish] verifying the candidate commit is on origin: {commit}")
        self.commit_on_origin(commit)
        existing_tag = self.tag_points_at(tag)
        if existing_tag is not None and existing_tag != commit:
            raise Refusal(f"tag {tag} already exists pointing at {existing_tag}, not {commit}")
        release = self.release_for_tag(tag)
        if release is None:
            print(f"[publish] creating draft release for tag {tag} at commit {commit[:12]}")
            release = self.call("POST", f"/repos/{repo}/releases", {
                "tag_name": tag,
                "target_commitish": commit,
                "name": context["release_name"],
                "body": context["notes"],
                "draft": True,
                "prerelease": self.config["prerelease"],
            })
        else:
            state_word = "published" if not release.get("draft") else "draft"
            print(f"[publish] adopting existing {state_word} release for tag {tag}")
        was_published = not release.get("draft")
        release_id = release["id"]

        # A published release is a public page. This tool never rewrites one in
        # place: an identical rerun re-verifies and touches nothing, a divergent
        # one is refused before the first DELETE.
        self.reconcile_and_upload(release_id, context, allow_changes=not was_published)
        self.verify_uploads(release_id, context, was_published=was_published)

        if was_published:
            print("[publish] release already published; assets re-verified, nothing changed")
            return {"release_id": release_id, "html_url": release.get("html_url")}

        final = self.call("PATCH", f"/repos/{repo}/releases/{release_id}", {"body": context["notes"]})
        flip = {"prerelease": self.config["prerelease"]}
        if self.config["stay_draft"]:
            self.call("PATCH", f"/repos/{repo}/releases/{release_id}", flip)
            print("[publish] leaving the release as a draft (--stay-draft)")
        else:
            flip["draft"] = False
            final = self.call("PATCH", f"/repos/{repo}/releases/{release_id}", flip)
            print("[publish] every asset verified against local bytes; release published")
        return {"release_id": release_id, "html_url": final.get("html_url")}

    def reconcile_and_upload(self, release_id: int, context: dict, *, allow_changes: bool) -> None:
        """Make the release's asset set equal the plan's, and nothing else.

        Every change is decided before anything is touched: skipping what
        matches, replacing what differs, deleting assets from an earlier
        attempt that this plan no longer contains (a stranded part-N from an
        old --part-mib would otherwise ride the page forever, outside both
        RELEASE-SHA256SUMS and verification).
        """
        existing = self.existing_assets(release_id)
        planned = context["plan"]["assets"]

        def delete_asset(asset_id: int, name: str) -> None:
            status, _ = self.transport.api(
                "DELETE", f"/repos/{self.config['repo']}/releases/assets/{asset_id}")
            if status != 204:
                raise ApiError(f"could not delete stale asset {name}: HTTP {status}")

        def upload_asset(name: str, asset: dict) -> None:
            status, body = self.upload_with_retry(release_id, asset)
            if status != 201:
                excerpt = json.dumps(body)[:400] if body else "(no body)"
                raise ApiError(f"upload of {name} refused: HTTP {status}: {excerpt}")
            print(f"[upload] {name}: {asset['size']:,} bytes uploaded")

        replace: dict[str, dict] = {}
        missing: list[str] = []
        for name, asset in sorted(planned.items()):
            current = existing.get(name)
            if current is not None:
                digest = current.get("digest")
                same_size = current.get("size") == asset["size"]
                same_digest = digest in (None, f"sha256:{asset['sha256']}")
                if same_size and same_digest:
                    print(f"[upload] {name}: already present and identical, skipping")
                else:
                    replace[name] = current
            else:
                missing.append(name)
        orphans = sorted(n for n in existing if n not in planned)

        pending = len(missing) + len(replace) + len(orphans)
        if pending and not allow_changes:
            raise Refusal(
                f"the published release disagrees with this tree: {len(missing)} missing, "
                f"{len(replace)} differing ({', '.join(sorted(replace)[:3]) or 'none'}), "
                f"{len(orphans)} unplanned ({', '.join(orphans[:3]) or 'none'}); "
                "refusing to rewrite a public page in place — delete the release or publish under another --tag")

        for name in orphans:
            print(f"[cleanup] {name}: deleting an asset this tree's plan does not contain")
            delete_asset(existing[name]["id"], name)
        for name, stale in sorted(replace.items()):
            print(f"[upload] {name}: present but differs (size {stale.get('size')} vs "
                  f"{planned[name]['size']}); replacing")
            delete_asset(stale["id"], name)
            upload_asset(name, planned[name])
        for name in missing:
            upload_asset(name, planned[name])

    def verify_uploads(self, release_id: int, context: dict, *, was_published: bool) -> None:
        print("[verify] re-reading the release; checking every asset against local bytes")
        existing = self.existing_assets(release_id)
        problems = []
        for name, asset in sorted(context["plan"]["assets"].items()):
            current = existing.get(name)
            if current is None:
                problems.append(f"{name}: missing from the release after upload")
            elif current.get("size") != asset["size"]:
                problems.append(f"{name}: server size {current.get('size')} != local {asset['size']}")
            elif current.get("digest") is not None and current["digest"] != f"sha256:{asset['sha256']}":
                problems.append(f"{name}: server digest {current['digest']} != local sha256:{asset['sha256']}")
        if problems:
            for problem in problems:
                print(f"[verify] MISMATCH {problem}", file=sys.stderr)
            hint = ("the release remains published with assets that do not match this tree; "
                    "do not download from it" if was_published else
                    "the release stays a draft — rerun to repair")
            raise VerifyFailure(f"{len(problems)} asset(s) failed verification; {hint}")


