def build_context(args: argparse.Namespace, work_dir: Path) -> dict:
    # Flag bounds first: refusing a bad --part-mib must not cost the full
    # multi-minute hashing pass over the tree that follows.
    if args.part_mib < 1:
        raise Refusal(f"--part-mib {args.part_mib} must be at least 1")
    part_bytes = args.part_mib * 1024 * 1024
    if part_bytes >= ASSET_LIMIT:
        raise Refusal(f"--part-mib {args.part_mib} produces parts at or over GitHub's per-file cap")

    tree = Path(args.tree).resolve()
    if not tree.is_dir():
        raise Refusal(f"--tree is not a directory: {tree}")
    manifest = load_manifest(tree)
    verified = verify_manifest_files(tree, manifest)
    medium_rel, medium = find_the_medium(tree, verified)
    require_evidence(tree, verified)
    provenance = cross_check_provenance(tree, manifest, medium_rel)
    boot = check_boot_verdict(tree)
    check_iso_digest_file(tree, verified[medium_rel]["sha256"])

    work_dir.mkdir(parents=True, exist_ok=True)
    plan = plan_assets(tree, verified, medium_rel, medium, work_dir, part_bytes)
    context = {
        "tree": tree, "manifest": manifest, "plan": plan, "provenance": provenance,
        "boot": boot,
        "tag": args.tag or manifest["imageVersion"],
        "release_name": args.release_name or f"Bunny OS {manifest['imageVersion']}",
        "notes": "", "work_dir": work_dir,
    }
    context["notes"] = render_notes(context)
    return context


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Publish a qualified media tree as a GitHub release.")
    parser.add_argument("--tree", required=True, help="media tree holding BUNNY-MANIFEST.json and the medium")
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "COMRADEART/bunny-os"),
                        help="owner/name to publish into")
    parser.add_argument("--tag", help="release tag (default: the manifest's imageVersion)")
    parser.add_argument("--release-name", help="human title (default: 'Bunny OS <imageVersion>')")
    parser.add_argument("--part-mib", type=int, default=DEFAULT_PART_MIB,
                        help=f"split size in MiB (default {DEFAULT_PART_MIB}; hard cap {ASSET_LIMIT // (1024 * 1024)})")
    parser.add_argument("--work-dir", help="where RELEASE-SHA256SUMS is staged (default: a fresh temp directory)")
    parser.add_argument("--dry-run", action="store_true",
                        help="validate, split and render everything; touch no network, need no token")
    parser.add_argument("--stay-draft", action="store_true", help="do not publish; leave the release a draft")
    parser.add_argument("--stable", action="store_true", help="mark the release non-prerelease")
    args = parser.parse_args(argv)

    work_dir = Path(args.work_dir) if args.work_dir else Path(tempfile.mkdtemp(prefix="bunny-publish-"))
    owned = args.work_dir is None
    try:
        context = build_context(args, work_dir)
        print(f"[plan] medium : {context['plan']['medium']['name']} ({context['plan']['medium']['size']:,} bytes)")
        print(f"[plan] sha256 : {context['plan']['medium']['sha256']}")
        print(f"[plan] tag    : {context['tag']} at commit {context['manifest']['sourceCommit'][:12]}")
        print(f"[plan] assets : {len(context['plan']['assets'])} (medium parts + evidence + {SUMS_NAME})")

        if args.dry_run:
            print("[dry-run] validation passed; no network calls were made")
            print("--- release notes preview ---")
            print(context["notes"])
            return 0

        token = (os.environ.get("GH_TOKEN") or os.environ.get("BUNNY_GITHUB_TOKEN") or "").strip()
        if not token:
            raise ConfigError("no GH_TOKEN (or BUNNY_GITHUB_TOKEN) in the environment")
        publisher = Publisher(
            {"repo": args.repo, "prerelease": not args.stable, "stay_draft": args.stay_draft},
            GithubTransport(token, args.repo),
        )
        result = publisher.run(context)
    finally:
        # Whatever happened — dry-run, refusal, mid-upload death — leave nothing
        # behind. Parts stream off the medium and never exist on disk; the sums
        # file is the only thing this script writes. A temp dir this script
        # created goes too; a caller-named --work-dir keeps its directory.
        try:
            (work_dir / SUMS_NAME).unlink()
        except OSError:
            pass
        if owned:
            shutil.rmtree(work_dir, ignore_errors=True)
    print(f"[done] {result.get('html_url')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
