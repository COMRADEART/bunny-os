// Write the two files that are derived from the design tokens.
//
//   shell/components/gnome-shell-extension/stylesheet.css
//       The default theme, rendered. GNOME auto-loads this when the extension
//       enables, and lib/themeManager.js replaces it a moment later with a sheet
//       rendered for the session's actual settings. It exists so that a desktop
//       whose theme manager failed is styled rather than bare — which means it
//       has to be a real sheet, and therefore has to be generated, because a
//       460-line default kept in step by hand is the arrangement this phase
//       replaced.
//
//   shell/themes/tokens.json
//       The same tokens for the Python side: the accessibility tests, the
//       Companion's phase table, the contrast thresholds. Generated rather than
//       parallel-maintained, because the two *were* parallel-maintained and
//       drifted into two entire palettes that shared no colour.
//
// Run with:  node build/scripts/render_design_assets.mjs
// Check with: python -m pytest tests/shell/test_design_tokens.py
//
// The check regenerates into a temporary directory and compares, so a committed
// file that does not match the tokens fails the suite rather than shipping.

import {mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const DESIGN = join(ROOT, 'shell', 'components', 'gnome-shell-extension', 'lib', 'design');

const tokens = await import(`file://${join(DESIGN, 'tokens.js')}`);
const {resolveTheme} = await import(`file://${join(DESIGN, 'theme.js')}`);
const {renderStylesheet} = await import(`file://${join(DESIGN, 'stylesheet.js')}`);

/**
 * The settings the shipped stylesheet is rendered for.
 *
 * The default session: dark, 100 %, animations on, normal contrast. Not a
 * "neutral" theme — there is no such thing — but the one a machine that has
 * never had a setting changed will actually show.
 */
export const DEFAULT_THEME_OPTIONS = {
    scheme: 'dark',
    highContrast: false,
    textScale: 1,
    reducedMotion: false,
    reducedTransparency: false,
};

export function defaultStylesheet() {
    return `${renderStylesheet(resolveTheme(DEFAULT_THEME_OPTIONS))}\n`;
}

/**
 * The token document for the Python consumers.
 *
 * `light` and `dark` stay at the top level under the names they have always had,
 * so a reader that only wants a colour keeps working; `themes` carries all four
 * including the high-contrast pair, which is what the accessibility gate needs.
 */
export function tokenDocument() {
    const themes = {};
    for (const [name, theme] of Object.entries(tokens.THEMES))
        themes[name] = {colour: theme.colour, shadow: theme.shadow, scheme: theme.scheme, highContrast: theme.highContrast};

    return {
        schemaVersion: tokens.SCHEMA_VERSION,
        generatedFrom: 'shell/components/gnome-shell-extension/lib/design/tokens.js',
        note: 'Generated by build/scripts/render_design_assets.mjs. Edit the JavaScript, not this file.',
        font: {ui: 'system-ui', monospace: 'monospace'},
        type: tokens.TYPE,
        textScale: {minimum: tokens.MIN_TEXT_SCALE, maximum: tokens.MAX_TEXT_SCALE, spaceRate: tokens.SPACE_SCALE_RATE},
        space: tokens.SPACE,
        radius: tokens.RADIUS,
        metric: tokens.METRIC,
        icon: tokens.ICON,
        light: tokens.THEMES.light.colour,
        dark: tokens.THEMES.dark.colour,
        themes,
        elevation: {
            levels: tokens.ELEVATION_LEVELS,
            dark: tokens.THEMES.dark.shadow,
            light: tokens.THEMES.light.shadow,
            highContrast: tokens.THEMES.highContrastDark.shadow,
        },
        motion: {
            instantMs: tokens.MOTION.instant,
            fastMs: tokens.MOTION.fast,
            standardMs: tokens.MOTION.normal,
            slowMs: tokens.MOTION.slow,
            reducedMs: tokens.MOTION.reduced,
            easeOut: tokens.MOTION.easeOut,
            easeInOut: tokens.MOTION.easeInOut,
        },
        focus: {
            widthPx: tokens.FOCUS.widthPx,
            highContrastWidthPx: tokens.FOCUS.highContrastWidthPx,
            offsetPx: tokens.FOCUS.offsetPx,
            insetOffsetPx: tokens.FOCUS.insetOffsetPx,
        },
        scrim: {dark: tokens.THEMES.dark.colour.scrim, light: tokens.THEMES.light.colour.scrim},
        companion: {sizePx: tokens.COMPANION_SIZE, phase: tokens.COMPANION_PHASE},
        risk: tokens.RISK,
        standing: tokens.STANDING,
        opacity: tokens.OPACITY,
        contrast: tokens.CONTRAST_THRESHOLDS,
        colourRoles: tokens.COLOUR_ROLES,
    };
}

export function tokenJson() {
    return `${JSON.stringify(tokenDocument(), null, 2)}\n`;
}

function write(path, contents) {
    mkdirSync(dirname(path), {recursive: true});
    writeFileSync(path, contents, 'utf8');
    process.stdout.write(`wrote ${path} (${contents.length} bytes)\n`);
}

// Only when run directly; the test imports the two functions above instead.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
    write(join(ROOT, 'shell', 'components', 'gnome-shell-extension', 'stylesheet.css'), defaultStylesheet());
    write(join(ROOT, 'shell', 'themes', 'tokens.json'), tokenJson());
}
