    rule(`.bunny-trust-risk { spacing: ${px(s.xs)}; }`);
    rule(`.bunny-trust-risk-glyph { icon-size: ${px(theme.icon.medium)}; }`);
    rule(`.bunny-trust-risk-label { ${type(theme, 'caption')} font-weight: 700; text-transform: uppercase; }`);
