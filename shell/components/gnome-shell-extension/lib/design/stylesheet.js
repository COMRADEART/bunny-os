// A resolved theme, rendered as St CSS.
//
// St's stylesheet language is a subset of CSS: no custom properties, no calc(),
// no flexbox, no media queries, no `:not()`, and no `var()`. That is why this is
// a function rather than a file. Everything the missing features would have done
// — a second palette, a scale factor, a contrast mode — happens in JavaScript
// before a single declaration is written, and what St receives is a flat sheet
// of literals it can parse.
//
// This module imports nothing and touches nothing. It takes a theme object and
// returns a string, so tests/shell/test_design_stylesheet.py can render all four
// themes at all four scales under node and assert on the text: that no
// `font-size` is absolute in the sense of being the same at 100 % and 200 %,
// that every reactive class has a `:focus` rule, and that the high-contrast
// sheet differs from the default one in more than a handful of bytes. Those are
// the three claims the accessibility run measured and disproved.
//
// ## The one rule about writing rules here
//
// Never write a literal. If a value is not `theme.something`, it is a value that
// cannot respond to a setting, and the whole failure this phase exists to fix
// was 43 font sizes and 151 colours that could not respond to a setting. The
// only exceptions are structural constants with no visual meaning — `1px` for a
// hairline divider's height, `0` — and `none`.

