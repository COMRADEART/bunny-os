    rule(`.bunny-standing-denied .bunny-standing-glyph, .bunny-standing-denied .bunny-standing-label { color: ${c.textSecondary}; }`);
    rule(`.bunny-standing-blocked .bunny-standing-glyph, .bunny-standing-blocked .bunny-standing-label { color: ${c.blocked}; }`);
    rule(`.bunny-standing-unenforced { border-color: ${c.warning}; }`);
    rule(`.bunny-standing-unenforced .bunny-standing-glyph, .bunny-standing-unenforced .bunny-standing-label { color: ${c.warning}; }`);
