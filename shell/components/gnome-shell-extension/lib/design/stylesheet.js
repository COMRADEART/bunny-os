    rule(`.bunny-task-stage { ${type(theme, 'caption')} color: ${c.textMuted}; }`);
    rule(`.bunny-task-stage-done { color: ${c.textSecondary}; }`);
    rule(`.bunny-task-stage-current { color: ${c.textPrimary}; font-weight: 600; }`);

