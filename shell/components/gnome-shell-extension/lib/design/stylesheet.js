    // Every standing is an icon, a word and a colour. Removing any one of the
    // three still leaves the state readable, which is the §19 requirement.
    rule(`.bunny-standing { spacing: ${px(s.xs)}; padding: ${px(s.xxs)} ${px(s.sm)}; border-radius: ${px(s.sm)}; border: 1px solid ${c.border}; }`);
    rule(`.bunny-standing-glyph { icon-size: ${px(theme.icon.small)}; }`);
    rule(`.bunny-standing-label { ${type(theme, 'caption')} font-weight: 600; }`);
