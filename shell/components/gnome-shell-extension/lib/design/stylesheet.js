const px = value => `${Math.round(value)}px`;

/**
 * `font-size`, `font-weight` and, for the monospace role, a family.
 *
 * Written from `theme.type[role]` so that the size at 150 % is 150 % of the size
 * at 100 % by construction rather than by a second table someone has to keep in
 * step.
 */
function type(theme, role) {
    const spec = theme.type[role];
    const family = spec.family === 'monospace' ? ' font-family: monospace;' : '';
    return `font-size: ${px(spec.size)}; font-weight: ${spec.weight};${family}`;
}

/** The one focus treatment. §13: identical everywhere, thicker at high contrast. */
function focusRule(selector, theme, {inset = false} = {}) {
    const offset = inset ? theme.focus.insetOffset : theme.focus.offset;
    return `${selector}:focus { outline: ${px(theme.focus.width)} solid ${theme.focus.colour}; outline-offset: ${px(offset)}; }`;
}

