    rule(`.bunny-trust-action-safe { border-color: ${c.borderStrong}; font-weight: 700; }`);
    rule(`.bunny-trust-action-allow { border-color: ${c.trust}; }`);
    rule(`.bunny-trust-disclosure { ${type(theme, 'caption')} color: ${c.accentText}; padding: ${px(s.xs)} ${px(s.sm)}; border-radius: ${px(s.sm)}; }`);
    rule(`.bunny-trust-disclosure:hover { background-color: ${c.accentSoft}; }`);
    focus('.bunny-trust-disclosure');
    rule(`.bunny-trust-details { spacing: ${px(s.xs)}; padding: ${px(s.sm)} ${px(s.md)}; border-radius: ${px(s.sm)}; background-color: ${c.surfaceRaised}; }`);
    rule(`.bunny-trust-detail { ${type(theme, 'mono')} color: ${c.textSecondary}; }`);

